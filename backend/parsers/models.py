from dataclasses import dataclass, asdict
from typing import Optional


@dataclass
class Product:

    # ==========================================================
    # Basic Information
    # ==========================================================

    product_name: str = ""
    description: str = ""
    brand: str = ""
    category: str = ""

    # ==========================================================
    # Pricing
    # ==========================================================

    price: Optional[float] = None
    old_price: Optional[float] = None
    discount_percent: Optional[float] = None
    currency: str = "USD"

    # ==========================================================
    # Rating
    # ==========================================================

    rating: Optional[float] = None
    reviews: int = 0

    # ==========================================================
    # Availability
    # ==========================================================

    in_stock: bool = True
    stock_count: Optional[int] = None

    # ==========================================================
    # Images
    # ==========================================================

    image: str = ""
    image_large: str = ""

    # ==========================================================
    # URLs
    # ==========================================================

    url: str = ""

    # ==========================================================
    # Marketplace
    # ==========================================================

    source: str = ""

    # ==========================================================
    # Amazon
    # ==========================================================

    asin: str = ""
    sponsored: bool = False
    prime: bool = False
    amazon_choice: bool = False
    best_seller: bool = False

    # ==========================================================
    # Shopify
    # ==========================================================

    shop_name: str = ""
    vendor: str = ""
    product_type: str = ""

    # ==========================================================
    # AliExpress
    # ==========================================================

    orders: int = 0
    shipping: str = ""
    shipping_price: Optional[float] = None

    # ==========================================================
    # Dropshipping
    # ==========================================================

    supplier: str = ""
    warehouse: str = ""

    # ==========================================================
    # Analytics
    # ==========================================================

    popularity_score: float = 0.0
    demand_score: float = 0.0
    competition_score: float = 0.0
    ai_score: float = 0.0

    # ==========================================================
    # Extra
    # ==========================================================

    raw_data: dict | None = None

    # ==========================================================
    # Convert
    # ==========================================================

    def to_dict(self):

        return asdict(self)